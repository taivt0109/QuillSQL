    /// <summary>
    /// The user interface language: English, or Vietnamese when chosen in Options (or when
    /// Windows is in Vietnamese and nothing is chosen). Text is written in English in the code
    /// and translated here; `{0}`, `{1}` stand for the parts that change.
    /// </summary>
    internal static class Loc
    {
        public static bool Vietnamese
        {
            get
            {
                var language = Settings.Current.Language;
                if (string.IsNullOrEmpty(language) || language == "auto")
                {
                    return CultureInfo.CurrentUICulture.TwoLetterISOLanguageName == "vi";
                }
                return language == "vi";
            }
        }

        /// <summary>The text in the chosen language.</summary>
        public static string T(string english)
        {
            if (string.IsNullOrEmpty(english) || !Vietnamese)
            {
                return english;
            }
            if (Vi.TryGetValue(english, out var exact))
            {
                return exact;
            }
            foreach (var template in Templates.Value)
            {
                var m = template.Item1.Match(english);
                if (m.Success)
                {
                    var args = Enumerable.Range(1, m.Groups.Count - 1).Select(i => (object)T(m.Groups[i].Value)).ToArray();
                    return string.Format(CultureInfo.CurrentCulture, template.Item2, args);
                }
            }
            return english;
        }

        // Built on first use: a static initializer here would run before the dictionary below exists.
        private static readonly Lazy<List<Tuple<Regex, string>>> Templates = new Lazy<List<Tuple<Regex, string>>>(() => Vi
            .Where(p => p.Key.Contains("{0}"))
            .OrderByDescending(p => p.Key.Length)
            .Select(p => Tuple.Create(new Regex("^" + Regex.Replace(Regex.Escape(p.Key), @"\\{\d}", "(.*?)") + "$", RegexOptions.Singleline), p.Value))
            .ToList());

