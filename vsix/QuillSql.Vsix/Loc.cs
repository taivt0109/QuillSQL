        /// <summary>An analysis message, `Title` or `Title: detail`, in the chosen language.</summary>
        public static string Issue(string message)
        {
            if (!Vietnamese || string.IsNullOrEmpty(message))
            {
                return message;
            }
            var colon = message.IndexOf(": ", StringComparison.Ordinal);
            return colon < 0 ? T(message) : T(message.Substring(0, colon)) + ": " + T(message.Substring(colon + 2));
        }
