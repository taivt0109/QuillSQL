/// The name of an event code.
pub fn name(code: i32) -> Option<&'static str> {
    EVENTS.binary_search_by_key(&code, |e| e.0).ok().map(|i| EVENTS[i].1)
}

/// The code of an event name (any case).
pub fn code(name: &str) -> Option<i32> {
    EVENTS.iter().find(|e| e.1.eq_ignore_ascii_case(name)).map(|e| e.0)
}
